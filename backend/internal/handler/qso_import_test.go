func TestParseADIFDataTypeIndicator(t *testing.T) {
	// LoTW / 部分日志软件会写成 <QSO_DATE:8:D>。类型指示不能把长度解析成 0，
	// 否则值里的 < 会把后面的字段切碎。
	raw := "<CALL:6>BI1KBU<QSO_DATE:8:D>20261101<TIME_ON:6:T>123045<COMMENT:13:S>a < b comment<EOR>"

	got := parseADIF(raw)

	if len(got) != 1 {
		t.Fatalf("期望 1 条记录，实际 %d", len(got))
	}
	if got[0]["QSO_DATE"] != "20261101" {
		t.Errorf("QSO_DATE = %q", got[0]["QSO_DATE"])
	}
	if got[0]["TIME_ON"] != "123045" {
		t.Errorf("TIME_ON = %q", got[0]["TIME_ON"])
	}
	if got[0]["COMMENT"] != "a < b comment" {
		t.Errorf("COMMENT = %q，类型指示下的长度应原样保留值里的 <", got[0]["COMMENT"])
	}
}

