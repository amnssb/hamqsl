func TestAdifDateRejectsInvalid(t *testing.T) {
	// 非法日期（13 月）原样返回，让导入侧自己按"缺少日期"跳过
	for _, v := range []string{"20261301", "2026-11-01", "", "abc"} {
		if got := adifDate(v); got != v {
			t.Errorf("%q 应原样返回，实际 %q", v, got)
		}
	}
}

func TestAdifTimeConvertsToHHMM(t *testing.T) {
	cases := map[string]string{
		"1230":   "12:30",
		"123045": "12:30",
		"":       "",
		"12":     "12",
	}
	for in, want := range cases {
		if got := adifTime(in); got != want {
			t.Errorf("adifTime(%q) = %q，期望 %q", in, got, want)
		}
	}
}

// adifLine 拼一条最小 ADIF 记录。date 必须是 8 位 YYYYMMDD。
func adifLine(call, date, freq, mode string) string {
	s := fmt.Sprintf("<CALL:%d>%s<QSO_DATE:8>%s", len(call), call, date)
	if freq != "" {
		s += fmt.Sprintf("<FREQ:%d>%s", len(freq), freq)
	}
	if mode != "" {
		s += fmt.Sprintf("<MODE:%d>%s", len(mode), mode)
	}
	return s + "<EOR>"
}

func TestImportADIFDedupAndSequence(t *testing.T) {
	db := newTestDB(t)

	// 库里已有一条：空频率空模式。再导同一条应跳过；同日不同模式应新增。
	db.Create(&model.QsoRecord{
		RecordCode: "SEED-1", CallSign: "BI1KBU", Date: "2026-11-01", SceneType: "QSO",
	})
	// 频率、模式为 NULL 的老行，和文件里的空字段算同一条。
	if err := db.Exec(`INSERT INTO qso_records (record_code, call_sign, date, freq, mode, scene_type, created_at, updated_at) VALUES ('SEED-NULL', 'NULLCS', '2026-11-03', NULL, NULL, 'QSO', datetime('now'), datetime('now'))`).Error; err != nil {
		t.Fatalf("插入 NULL 频率的旧记录失败: %v", err)
	}

	raw := adifLine("BI1KBU", "20261101", "", "SSB") + // 同日但模式不同，算新的
		adifLine("bi1kbu", "20261101", "", "") + // 呼号大小写不同，规范化后与库里那条重复
		adifLine("BI1KBU", "20261101", "", "") + // 文件内再重复一次
		adifLine("XX1YYY", "20261102", "14.074", "FT8") +
		adifLine("NULLCS", "20261103", "", "") + // 对上库里的 NULL 频率/模式
		"<CALL:6>NOCALL<EOR>" // 没有日期，跳过

	imported, skipped, err := importADIF(db, []byte(raw))
	if err != nil {
		t.Fatalf("导入失败: %v", err)
	}
	if imported != 2 || skipped != 4 {
		t.Fatalf("期望新增 2 跳过 4，实际新增 %d 跳过 %d", imported, skipped)
	}

	again, skippedAgain, err := importADIF(db, []byte(raw))
	if err != nil {
		t.Fatalf("第二次导入失败: %v", err)
	}
	if again != 0 || skippedAgain != 6 {
		t.Fatalf("重复导入应全部跳过（无日期的那条也算跳过），实际新增 %d 跳过 %d", again, skippedAgain)
	}

	// 第一次领了 2 个号，第二次一个没领。下一个单取必须是 3。
	if got := nextQsoRecordCode(db); got != "QSO-000003" {
		t.Errorf("导入之后的下一个编号应为 QSO-000003，实际 %q", got)
	}
}

// 跨过一批 100 行，确认第二批也写进去了，编号连续。
func TestImportADIFCrossesBatchBoundary(t *testing.T) {
	db := newTestDB(t)

	var b []byte
	const n = 120
	for i := 1; i <= n; i++ {
		call := fmt.Sprintf("B%05d", i)
		b = append(b, adifLine(call, "20261101", "7.074", "FT8")...)
	}
	imported, skipped, err := importADIF(db, b)
	if err != nil {
		t.Fatalf("导入失败: %v", err)
	}
	if imported != n || skipped != 0 {
		t.Fatalf("期望新增 %d 跳过 0，实际新增 %d 跳过 %d", n, imported, skipped)
	}

	var count int64
	db.Model(&model.QsoRecord{}).Count(&count)
	if count != int64(n) {
		t.Fatalf("库里应有 %d 行，实际 %d", n, count)
	}
	var last model.QsoRecord
	db.Where("call_sign = ?", "B00120").First(&last)
	if last.RecordCode != "QSO-000120" {
		t.Errorf("最后一条编号应为 QSO-000120，实际 %q", last.RecordCode)
	}
}

// 通联换卡只拉还没建卡的记录。has_card=false 必须在库里滤掉，
// 否则最近一页全是已建卡时，更早的未建卡记录出不来。
func TestListQsoFiltersHasCard(t *testing.T) {
	db := newTestDB(t)
	db.Create(&model.QsoRecord{RecordCode: "QSO-000001", CallSign: "AAA", Date: "2026-11-01", HasCard: true})
	db.Create(&model.QsoRecord{RecordCode: "QSO-000002", CallSign: "BBB", Date: "2026-11-02", HasCard: false})

	gin.SetMode(gin.TestMode)
	rec := httptest.NewRecorder()
	c, _ := gin.CreateTestContext(rec)
	c.Request = httptest.NewRequest(http.MethodGet, "/api/qso-records?has_card=false", nil)
	NewQsoHandler(db).List(c)

	var body struct {
		Data struct {
			Items []model.QsoRecord `json:"items"`
			Total int64             `json:"total"`
		} `json:"data"`
	}
	if err := json.Unmarshal(rec.Body.Bytes(), &body); err != nil {
		t.Fatalf("解析响应失败: %v body=%s", err, rec.Body.String())
	}
	if body.Data.Total != 1 || len(body.Data.Items) != 1 || body.Data.Items[0].CallSign != "BBB" {
		t.Fatalf("has_card=false 应只返回 BBB，实际 total=%d items=%+v", body.Data.Total, body.Data.Items)
	}
}
